"""Rescore every stored DocVQA row with the current docvqa_eval_core matcher. No API calls.

Run from the DocVQA directory, on either side. It re-derives the `score` column from the stored
`model_response` and rewrites the result files and their overall CSVs, stamping SCORER_VERSION.
ANLS is not touched — it was always graded and never had this problem.

Written for the v1 -> docvqa_lenient_v2 rescore of 2026-09-11, and kept because the scorer will
change again: a stored number under one version cannot be compared with one under another, and
this is what makes the transition reproducible rather than a thing someone did once by hand.

The two generations of result file are handled separately because they have different shapes — the
DOCVQA_* slots are jsonl written by the core, the four older ones are standalone CSVs.
"""
import ast, csv, glob, json, os, re, sys
sys.path.insert(0, '.')
import docvqa_eval_core as core

def golds(raw):
    try: return json.loads(raw)
    except Exception: return ast.literal_eval(raw)

print("=== new-shape slots (jsonl + csv + overall regenerated by the core) ===")
for jl in sorted(glob.glob('DOCVQA_*/results/*.jsonl')):
    model_dir = jl.split('/')[0]
    base = os.path.basename(jl)[:-6]
    m = re.search(r'_shard\d+of\d+$', base)
    tag = m.group(0) if m else ""
    slug = base[:-len(tag)] if tag else base
    rows = [json.loads(l) for l in open(jl) if l.strip()]
    model_id = {"gpt-5_6-luna": "gpt-5.6-luna",
                "gemini-3_5-flash-lite": "gemini-3.5-flash-lite"}[slug]
    before = sum(r["score"] for r in rows)
    for r in rows:
        g = golds(r["gold_answers"]) if isinstance(r["gold_answers"], str) else r["gold_answers"]
        r["score"] = core.score_response("Final Answer: " + r["final_answer"], g)
    cfg = core.parse_config(rows[0].get("config", "")) or None
    core.write_results(model_dir, model_id, rows, config=cfg, tag=tag)
    print(f"  {jl:62} {before} -> {sum(r['score'] for r in rows)}")

print("=== standalone-runner files (score column rewritten in place, scorer column added) ===")
OLD = {"gemini_docvqa_results.csv": "gemini_docvqa_overall.csv",
       "openai_docvqa_results.csv": "openai_docvqa_overall.csv",
       "qwen_DocVQA/qwen_docvqa_results.csv": "qwen_DocVQA/qwen_docvqa_overall.csv",
       "gemma_DocVQA/gemma_docvqa_results_half1.csv": "gemma_DocVQA/gemma_docvqa_overall_half1.csv",
       "gemma_DocVQA/gemma_docvqa_results_half2.csv": "gemma_DocVQA/gemma_docvqa_overall_half2.csv"}
for src, overall in OLD.items():
    # The two sides do not hold the same set: qwen_DocVQA/ and gemma_DocVQA/ are local-only, and
    # a missing file is not a reason to leave the ones after it unrescored.
    if not os.path.exists(src):
        print(f"  {src:62} absent here, skipped")
        continue
    rows = list(csv.DictReader(open(src)))
    fields = [f for f in rows[0] if f != "scorer"] + ["scorer"]
    before = sum(int(float(r["score"])) for r in rows)
    for r in rows:
        r["score"] = core.score_response("Final Answer: " + core.extract_final_answer(r["model_response"]),
                                         golds(r["gold_answers"]))
        r["scorer"] = core.SCORER_VERSION
    with open(src, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields); w.writeheader()
        for r in rows: w.writerow({k: r.get(k, "") for k in fields})
    n = len(rows)
    acc = sum(r["score"] for r in rows) / n
    anls = sum(float(r["anls"]) for r in rows) / n
    with open(overall, "w", newline="") as fh:
        w = csv.writer(fh); w.writerow(["dataset", "accuracy", "anls", "scorer"])
        w.writerow(["docvqa_validation", acc, anls, core.SCORER_VERSION])
    print(f"  {src:62} {before} -> {sum(r['score'] for r in rows)}  (n={n}, acc={acc:.4f})")
